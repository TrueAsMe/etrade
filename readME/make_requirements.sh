#!/usr/bin/env bash
# make_requirements.sh — generate an EXACT, reproducible requirements.txt
# from the active Python 3.11 virtualenv in this project.
#
# Run from the project root:
#   cd ~/prod/em_algo_v4
#   bash make_requirements.sh
#
set -euo pipefail
cd "$(dirname "$0")"

# 1. Activate the project venv (Python 3.11)
if [ ! -d "env" ]; then
  echo "ERROR: env/ virtualenv not found in $(pwd)"; exit 1
fi
# shellcheck disable=SC1091
source env/bin/activate

# 2. Confirm interpreter version + location (catch wrong-env mistakes early)
PYV="$(python -c 'import sys; print("%d.%d" % sys.version_info[:2])')"
echo "Using Python ${PYV} from $(which python)"
[ "${PYV}" = "3.11" ] || echo "WARNING: expected Python 3.11, got ${PYV}"

# 3. Strip known-stray packages that keep re-entering the freeze.
#    'lab' and 'txt2tags' were never project deps — accidental installs that
#    kept returning via the install -> freeze -> install loop. Remove defensively.
pip uninstall -y lab txt2tags >/dev/null 2>&1 || true

# 4. Guarantee required deps are present BEFORE freezing.
#    python-dotenv -> config.py | ipykernel -> VS Code/Jupyter kernel
#    (ipython is intentionally NOT upgraded: 9.11+ requires Python 3.12,
#     so on 3.11 we keep whatever 3.11-compatible version is installed.)
pip install --quiet --upgrade python-dotenv ipykernel
python -c "import dotenv"    && echo "python-dotenv import OK"
python -c "import ipykernel" && echo "ipykernel import OK"

# 5. Exact freeze of the live environment
pip freeze > requirements.txt
COUNT="$(wc -l < requirements.txt | tr -d ' ')"
echo "Wrote requirements.txt (${COUNT} pinned packages)"

# 6. Sanity checks — fail loudly if the file is incomplete or junk returned
fail=0
grep -qi "^python-dotenv==" requirements.txt || { echo "WARNING: python-dotenv missing"; fail=1; }
grep -qi "^ipykernel=="     requirements.txt || { echo "WARNING: ipykernel missing";     fail=1; }
if grep -qiE '^(lab|txt2tags)==' requirements.txt; then
  echo "WARNING: stray package (lab/txt2tags) reappeared — investigate with: pipdeptree"
  fail=1
fi
if grep -qiE '^ipython==9\.(1[1-9]|[2-9][0-9])' requirements.txt; then
  echo "WARNING: ipython >= 9.11 pinned — needs Python 3.12, will fail to install on 3.11"
  fail=1
fi
[ "$fail" = "0" ] && echo "Verified: requirements.txt is clean, complete, and 3.11-installable"

# NOTE: requirements-prod.txt is hand-curated (cloud runtime only) and is NOT
# regenerated by this script. Edit it by hand when runtime deps change.
